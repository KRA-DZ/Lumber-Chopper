import { sprite, random } from "./pixel-art.js";

// Малые предметы используют ту же сетку, что герой и основные постройки.
// Все растры готовятся один раз; декор не добавляет физических препятствий.
export function createWorldArt() {
  const out = {};
  out.moss = sprite(36, 12, 18, 7, (p) => {
    p.oval(18, 7, 17, 4, "#36763d");
    const rnd = random(17);
    for (let i = 0; i < 26; i++)
      p.rect(
        4 + rnd() * 27,
        4 + rnd() * 6,
        3,
        1,
        i % 3 ? "#62974a" : "#94b35b",
      );
  });
  out.roots = sprite(38, 17, 19, 8, (p) => {
    for (const [x, y] of [
      [2, 13],
      [9, 2],
      [35, 12],
      [30, 3],
    ]) {
      p.line(19, 5, x, y, "#5f5934", 3);
      p.line(19, 4, x, y - 1, "#9a8550");
    }
    p.rect(6, 12, 7, 1, "#71924a");
    p.rect(28, 10, 5, 2, "#628849");
  });
  out.berry = sprite(34, 27, 17, 24, (p) => {
    p.oval(17, 21, 16, 5, "#315c35");
    for (const [x, y, r] of [
      [10, 15, 8],
      [21, 13, 10],
      [17, 8, 7],
    ]) {
      p.oval(x, y, r, r * 0.65, "#315f39");
      p.oval(x, y - 2, r - 2, r * 0.46, "#58914a");
      p.rect(x - 3, y - 4, 4, 1, "#8db45a");
    }
    for (const [x, y] of [
      [8, 14],
      [19, 8],
      [25, 15],
      [14, 19],
      [20, 17],
    ]) {
      p.rect(x, y, 3, 3, "#823f52");
      p.rect(x, y, 1, 1, "#dc8b84");
    }
  });
  out.saplings = [0, 1].map((v) =>
    sprite(30, 38, 15, 35, (p) => {
      p.line(15, 34, 15, 15, "#654c31", 2);
      p.line(15, 26, 9, 21, "#906b3e");
      for (const [x, y, r] of [
        [14, 12, 9],
        [10, 19, 8],
        [21, 20, 7],
      ]) {
        p.oval(x, y, r, r * 0.85, v ? "#3c6941" : "#34613b");
        p.oval(x, y - 2, r - 2, r * 0.6, v ? "#81aa58" : "#679c4d");
        p.rect(x - 3, y - 4, 4, 2, "#a0bc68");
      }
    }),
  );
  out.log = sprite(92, 36, 46, 29, (p) => {
    p.oval(47, 27, 43, 6, "#315c32");
    p.poly(
      [
        [9, 12],
        [78, 4],
        [84, 23],
        [14, 31],
      ],
      "#583f2b",
    );
    p.poly(
      [
        [12, 13],
        [78, 7],
        [81, 20],
        [16, 27],
      ],
      "#93653c",
    );
    for (let i = 0; i < 6; i++)
      p.line(19 + i * 10, 12 - i, 24 + i * 10, 24 - i, "#5e462e", 2);
    p.line(18, 14, 72, 8, "#c09254", 2);
    p.oval(13, 21, 10, 12, "#58442b");
    p.oval(13, 20, 8, 10, "#c3985a");
    p.oval(13, 20, 5, 7, "#957140");
    p.oval(13, 20, 3, 5, "#d1aa69");
    p.oval(13, 20, 1, 2, "#785d37");
    p.line(52, 8, 56, 1, "#654b2f", 3);
    p.line(57, 1, 63, 1, "#654b2f", 2);
    for (const x of [33, 43, 57, 65]) {
      p.rect(x, 8, 7, 3, "#527b3e");
      p.rect(x + 1, 7, 4, 1, "#8ca34d");
    }
  });
  out.spring = sprite(100, 65, 50, 46, (p) => {
    p.oval(50, 44, 45, 17, "#2c603d");
    p.oval(49, 44, 37, 13, "#8d9571");
    p.oval(49, 44, 31, 10, "#3b8290");
    p.oval(48, 42, 26, 7, "#5ba5a0");
    for (const [x, y] of [
      [22, 36],
      [34, 31],
      [65, 33],
      [78, 42],
      [23, 49],
      [66, 54],
    ]) {
      p.oval(x, y, 8, 5, "#525e4c");
      p.oval(x, y - 2, 6, 3, "#a1ac81");
      p.rect(x - 2, y - 3, 3, 1, "#ced0a2");
    }
    p.poly(
      [
        [39, 31],
        [42, 5],
        [60, 4],
        [67, 32],
      ],
      "#506452",
    );
    p.poly(
      [
        [44, 29],
        [45, 7],
        [56, 6],
        [61, 29],
      ],
      "#8d9e78",
    );
    p.rect(46, 8, 4, 15, "#b0b68a");
    p.rect(53, 23, 6, 5, "#334d42");
    p.rect(54, 27, 3, 14, "#83c7ba");
    p.rect(55, 28, 1, 14, "#d8e9ce");
    p.line(39, 44, 50, 44, "#a5d6c1");
    p.line(56, 47, 67, 47, "#83c7ba");
    p.rect(36, 25, 8, 4, "#4f803f");
    p.rect(60, 11, 6, 3, "#5b8849");
  });
  out.arch = sprite(104, 98, 52, 91, (p) => {
    const blocks = [
      [11, 80],
      [13, 66],
      [13, 52],
      [14, 38],
      [20, 24],
      [31, 14],
      [46, 9],
      [61, 12],
      [74, 23],
      [81, 38],
      [81, 53],
      [80, 68],
      [81, 82],
    ];
    blocks.forEach(([x, y], i) => {
      p.border(x, y, 16, 13, "#465748", i % 2 ? "#8a997b" : "#9eaa86");
      p.rect(x + 2, y + 2, 12, 2, "#c3c7a0");
      p.rect(x + 11, y + 6, 3, 5, "#708268");
      if (i % 3 === 0) p.rect(x + 2, y + 9, 7, 3, "#517e42");
    });
    p.line(23, 24, 23, 51, "#46713c", 2);
    p.rect(20, 31, 6, 3, "#6a974a");
    p.line(85, 42, 85, 73, "#4c773d", 2);
    p.rect(82, 58, 6, 3, "#7a9b50");
    for (const [x, y] of [
      [5, 90],
      [29, 92],
      [70, 91],
      [93, 89],
    ]) {
      p.rect(x, y, 8, 3, "#617d46");
      p.rect(x + 2, y - 2, 2, 4, "#9aaf60");
    }
  });
  out.tools = sprite(34, 45, 17, 40, (p) => {
    p.border(2, 25, 30, 15, "#5a4630", "#9d7946");
    for (let x = 5; x < 30; x += 6) p.rect(x, 28, 1, 10, "#c5a365");
    p.line(11, 34, 16, 4, "#63482e", 3);
    p.line(12, 33, 17, 5, "#c3985b");
    p.poly(
      [
        [15, 5],
        [28, 3],
        [28, 12],
        [15, 10],
      ],
      "#344b46",
    );
    p.rect(24, 4, 3, 7, "#a5b1a0");
    p.line(20, 30, 28, 18, "#c3a06a", 2);
    p.line(23, 20, 30, 25, "#73857a", 3);
  });
  out.supplies = sprite(48, 33, 24, 29, (p) => {
    p.border(2, 12, 25, 17, "#604730", "#a57b42");
    for (const x of [5, 13, 22]) p.rect(x, 14, 2, 13, "#d5ad6c");
    p.line(5, 14, 23, 26, "#654b30", 2);
    p.oval(36, 23, 10, 7, "#766c43");
    p.oval(36, 21, 8, 7, "#b6a67a");
    p.rect(32, 14, 7, 3, "#665b3b");
    p.line(34, 15, 39, 15, "#dfc99a");
  });
  out.clothes = [0, 1].map((frame) =>
    sprite(92, 50, 46, 44, (p) => {
      for (const x of [4, 86]) {
        p.rect(x, 7, 3, 38, "#674e33");
        p.rect(x + 1, 8, 1, 34, "#bc9559");
      }
      p.line(6, 10, 44, 15, "#b4a17a");
      p.line(44, 15, 87, 10, "#b4a17a");
      for (const [x, c] of [
        [18, "#c0c4ac"],
        [44, "#6e8d91"],
        [65, "#b58364"],
      ]) {
        const shift = frame ? 1 : 0;
        p.rect(x + shift, 15, 14, 18, c);
        p.rect(x + 3 + shift, 17, 2, 15, "#00000016");
        p.rect(x + 1, 13, 2, 4, "#ddc48d");
        p.rect(x + 11, 13, 2, 4, "#ddc48d");
      }
    }),
  );
  out.bench = sprite(54, 27, 27, 23, (p) => {
    p.border(3, 8, 48, 10, "#55452d", "#b68b4f");
    p.rect(5, 9, 44, 2, "#d6af69");
    p.rect(8, 18, 4, 7, "#65492f");
    p.rect(42, 18, 4, 7, "#65492f");
    p.line(12, 20, 43, 20, "#806039", 2);
  });
  out.firewood = sprite(48, 32, 24, 28, (p) => {
    for (let row = 0; row < 3; row++)
      for (let i = 0; i < 4 - row; i++) {
        const x = 7 + i * 10 + row * 5,
          y = 25 - row * 8;
        p.oval(x, y, 6, 4, "#583f2a");
        p.oval(x, y - 1, 4, 3, "#c09456");
        p.rect(x, y - 2, 1, 3, "#8e6b3f");
      }
    p.rect(2, 28, 44, 2, "#4c5032");
  });
  out.smoke = sprite(34, 26, 17, 13, (p) => {
    p.oval(13, 15, 11, 8, "#c4c7b0");
    p.oval(23, 12, 9, 7, "#c4c7b0");
    p.oval(15, 8, 8, 6, "#d6d7c0");
  });
  out.fog = sprite(128, 32, 64, 16, (p) => {
    const rnd = random(91);
    for (let i = 0; i < 15; i++)
      p.oval(
        12 + rnd() * 104,
        10 + rnd() * 13,
        12 + rnd() * 16,
        3 + rnd() * 5,
        "#b6cbb4",
      );
    // Дизеринг по краю вместо размытия большого изображения каждый кадр.
    for (let y = 0; y < 32; y++)
      for (let x = 0; x < 128; x++)
        if ((x + y) % 3 === 0) p.g.clearRect(x, y, 1, 1);
  });
  out.note = sprite(26, 24, 13, 18, (p) => {
    p.oval(13, 19, 12, 3, "#426637");
    p.poly(
      [
        [5, 4],
        [22, 6],
        [20, 20],
        [4, 18],
      ],
      "#755b36",
    );
    p.poly(
      [
        [6, 5],
        [21, 7],
        [19, 19],
        [5, 17],
      ],
      "#d8c38b",
    );
    p.line(9, 9, 17, 10, "#8e7850");
    p.line(8, 12, 16, 13, "#8e7850");
    p.line(8, 15, 13, 15, "#8e7850");
  });
  out.strangeTracks = sprite(52, 48, 26, 38, (p) => {
    for (const [x, y] of [
      [11, 29],
      [35, 12],
    ])
      for (let i = 0; i < 3; i++) {
        p.line(x + i * 4, y, x + i * 4 + 2, y - 7, "#456635", 2);
        p.line(x + i * 4 + 1, y, x + i * 4 + 3, y - 6, "#8e8653");
      }
  });
  out.rune = sprite(22, 32, 11, 27, (p) => {
    p.poly(
      [
        [5, 4],
        [16, 2],
        [21, 28],
        [2, 29],
      ],
      "#495b4a",
    );
    p.poly(
      [
        [7, 5],
        [15, 4],
        [18, 26],
        [4, 27],
      ],
      "#879377",
    );
    p.line(7, 9, 14, 9, "#435d50");
    p.line(6, 10, 6, 18, "#435d50");
    p.line(7, 19, 14, 19, "#435d50");
    p.line(15, 10, 15, 14, "#435d50");
    p.rect(11, 17, 3, 2, "#bed0ad");
  });
  return out;
}
